<script>
(function () {
  "use strict";

  // Footer Year
  const yearEl = document.getElementById("currentYear");
  if (yearEl) yearEl.textContent = new Date().getFullYear();

  // Header Scroll & Mobile Nav
  const header = document.querySelector(".site-header");
  const navToggle = document.querySelector(".nav-toggle");
  const mainNav = document.querySelector(".main-nav");

  function onScrollHeader() {
    if (!header) return;
    header.classList.toggle("is-scrolled", window.scrollY > 12);
  }
  window.addEventListener("scroll", onScrollHeader, { passive: true });
  onScrollHeader();

  if (navToggle && mainNav) {
    navToggle.addEventListener("click", () => {
      const isOpen = mainNav.style.display === "block";
      mainNav.style.display = isOpen ? "none" : "block";
      navToggle.setAttribute("aria-expanded", String(!isOpen));
    });

    mainNav.querySelectorAll("a").forEach((link) => {
      link.addEventListener("click", () => {
        if (window.matchMedia("(max-width: 1024px)").matches) {
          mainNav.style.display = "none";
          navToggle.setAttribute("aria-expanded", "false");
        }
      });
    });
  }

  // Scroll Reveal
  const revealEls = document.querySelectorAll(".reveal");
  if ("IntersectionObserver" in window && revealEls.length) {
    const observer = new IntersectionObserver(
      (entries) => {
        entries.forEach((entry) => {
          if (entry.isIntersecting) {
            entry.target.classList.add("is-visible");
            observer.unobserve(entry.target);
          }
        });
      },
      { threshold: 0.12, rootMargin: "0px 0px -60px 0px" }
    );
    revealEls.forEach((el) => observer.observe(el));
  } else {
    revealEls.forEach((el) => el.classList.add("is-visible"));
  }

  // FAQ Accordion
  document.querySelectorAll(".faq-item__question").forEach((btn) => {
    btn.addEventListener("click", () => {
      const item = btn.closest(".faq-item");
      const answer = item.querySelector(".faq-item__answer");
      const isOpen = item.classList.contains("is-open");

      document.querySelectorAll(".faq-item.is-open").forEach((openItem) => {
        if (openItem !== item) {
          openItem.classList.remove("is-open");
          openItem.querySelector(".faq-item__answer").style.maxHeight = null;
        }
      });

      item.classList.toggle("is-open", !isOpen);
      answer.style.maxHeight = !isOpen ? answer.scrollHeight + "px" : null;
      btn.setAttribute("aria-expanded", String(!isOpen));
    });
  });

  // Modal Controls
  const modalOverlay = document.getElementById("orderModal");
  const orderForm = document.getElementById("orderForm");
  const productSelect = document.getElementById("yantraSelect");
  const sizeSelect = document.getElementById("sizeSelect");
  const summaryLabel = document.getElementById("orderSummaryLabel");
  const modalTitle = document.getElementById("modalTitle");

  const PRODUCT_LABELS = {
    mahamrityunjay: "Maha Mrityunjaya Yantra",
    kaalbhairav: "Shree Kalbhairav Yantra"
  };

  function updateOrderSummary() {
    if (!sizeSelect || !summaryLabel) return;
    const productKey = productSelect ? productSelect.value : 'mahamrityunjay';
    const sizeVal = sizeSelect.value;
    const sizeText = sizeVal === '5x5' ? '5 × 5 Inch' : '3 × 3 Inch';
    const productLabel = PRODUCT_LABELS[productKey] || "Maha Mrityunjaya Yantra";
    summaryLabel.textContent = `${productLabel} (${sizeText})`;
    if (modalTitle) {
      modalTitle.textContent = `Order ${productLabel}`;
    }
  }

  function openOrderModal(productKey, sizeKey) {
    if (!modalOverlay) return;
    if (productSelect && productKey) productSelect.value = productKey;
    if (sizeSelect && sizeKey) sizeSelect.value = sizeKey;
    updateOrderSummary();
    modalOverlay.classList.add("is-open");
    document.body.style.overflow = "hidden";
    const firstField = orderForm.querySelector("input, select");
    if (firstField) setTimeout(() => firstField.focus(), 250);
  }

  if (productSelect) productSelect.addEventListener("change", updateOrderSummary);
  if (sizeSelect) sizeSelect.addEventListener("change", updateOrderSummary);

  function closeOrderModal() {
    if (!modalOverlay) return;
    modalOverlay.classList.remove("is-open");
    document.body.style.overflow = "";
  }

  document.querySelectorAll("[data-open-order]").forEach((trigger) => {
    trigger.addEventListener("click", (e) => {
      e.preventDefault();
      openOrderModal(trigger.dataset.yantra, trigger.dataset.size);
    });
  });

  document.querySelectorAll("[data-close-order]").forEach((btn) => {
    btn.addEventListener("click", closeOrderModal);
  });

  if (modalOverlay) {
    modalOverlay.addEventListener("click", (e) => {
      if (e.target === modalOverlay) closeOrderModal();
    });
  }

  document.addEventListener("keydown", (e) => {
    if (e.key === "Escape" && modalOverlay && modalOverlay.classList.contains("is-open")) {
      closeOrderModal();
    }
  });

  // Toast Function
  function showToast(message) {
    const toast = document.getElementById("toast");
    if (!toast) return;
    toast.textContent = message;
    toast.classList.add("is-visible");
    setTimeout(() => {
      toast.classList.remove("is-visible");
    }, 4000);
  }

  // Field Errors
  function showFieldError(field, message) {
    field.setAttribute("aria-invalid", "true");
    field.style.borderColor = "#B03C30";
    let hint = field.parentElement.querySelector(".field-error");
    if (!hint) {
      hint = document.createElement("span");
      hint.className = "field-error";
      hint.style.color = "#B03C30";
      hint.style.fontSize = "0.78rem";
      hint.style.marginTop = "0.2rem";
      field.parentElement.appendChild(hint);
    }
    hint.textContent = message;
  }

  function clearFieldError(field) {
    field.removeAttribute("aria-invalid");
    field.style.borderColor = "";
    const hint = field.parentElement.querySelector(".field-error");
    if (hint) hint.remove();
  }

  function validateOrderForm(form) {
    let isValid = true;
    const requiredFields = form.querySelectorAll("[required]");

    requiredFields.forEach((field) => {
      clearFieldError(field);
      if (!field.value || !field.value.trim()) {
        showFieldError(field, "This field is required");
        isValid = false;
        return;
      }
      if (field.type === "tel") {
        const digits = field.value.replace(/\D/g, "");
        if (digits.length < 10) {
          showFieldError(field, "Please enter a valid 10-digit mobile number");
          isValid = false;
        }
      }
      if (field.type === "email" && field.value) {
        const emailPattern = /^[^\s@]+@[^\s@]+\.[^\s@]+$/;
        if (!emailPattern.test(field.value)) {
          showFieldError(field, "Please enter a valid email address");
          isValid = false;
        }
      }
      if (field.id === "pincode" && field.value) {
        if (!/^\d{6}$/.test(field.value.trim())) {
          showFieldError(field, "Please enter a valid 6-digit pincode");
          isValid = false;
        }
      }
    });

    return isValid;
  }

  // Submit Order Form & Razorpay Integration
  if (orderForm) {
    orderForm.addEventListener("submit", function (e) {
      e.preventDefault();
      if (!validateOrderForm(orderForm)) {
        showToast("Please fill in all required fields accurately.");
        return;
      }

      const submitBtn = orderForm.querySelector('[type="submit"]');
      const originalText = submitBtn ? submitBtn.textContent : "";
      if (submitBtn) {
        submitBtn.disabled = true;
        submitBtn.textContent = "Processing Order...";
      }

      const formData = new FormData(orderForm);
      const productKey = formData.get("yantra") || "mahamrityunjay";
      const productName = PRODUCT_LABELS[productKey] || "Maha Mrityunjaya Yantra";
      const payload = {
        product_name: productName,
        size: formData.get("size") || "3x3",
        customer_name: formData.get("customer_name"),
        mobile: formData.get("mobile"),
        email: formData.get("email"),
        gotra: formData.get("gotra"),
        sankalp: formData.get("sankalp"),
        address: formData.get("address"),
        city: formData.get("city"),
        state: formData.get("state"),
        pincode: formData.get("pincode"),
      };

      fetch('api/create_us_order.php', {
        method: 'POST',
        headers: { 'Content-Type': 'application/json' },
        body: JSON.stringify(payload)
      })
      .then(r => r.json())
      .then(res => {
        if (res.status === 'success') {
          launchRazorpay(payload, res, submitBtn, originalText);
        } else {
          showToast(res.message || "Could not create order. Please try again.");
          if (submitBtn) { submitBtn.disabled = false; submitBtn.textContent = originalText; }
        }
      })
      .catch(err => {
        console.error(err);
        showToast("Network error. Please try again.");
        if (submitBtn) { submitBtn.disabled = false; submitBtn.textContent = originalText; }
      });
    });
  }

  function launchRazorpay(payload, serverOrder, submitBtn, originalText) {
    if (typeof Razorpay === "undefined") {
      showToast("Razorpay SDK failed to load. Please refresh the page.");
      if (submitBtn) { submitBtn.disabled = false; submitBtn.textContent = originalText; }
      return;
    }

    var options = {
      key: serverOrder.key_id,
      amount: serverOrder.amount,
      currency: serverOrder.currency,
      order_id: serverOrder.order_id,
      name: "Vastu Mitra Abhishek",
      description: payload.product_name + " (Pure Copper)",
      image: "assets/logo/logo.png",
      prefill: {
        name: payload.customer_name,
        email: payload.email,
        contact: payload.mobile,
      },
      theme: { color: "#B5652D" },
      handler: function (response) {
        fetch('api/verify_us_payment.php', {
          method: 'POST',
          headers: { 'Content-Type': 'application/json' },
          body: JSON.stringify({
            razorpay_order_id: response.razorpay_order_id,
            razorpay_payment_id: response.razorpay_payment_id,
            razorpay_signature: response.razorpay_signature,
          }),
        })
        .then(r => r.json())
        .then(vData => {
          if (vData.status === 'success' || vData.status === 'info') {
            closeOrderModal();
            document.getElementById('confirmRefId').textContent = 'Order DB ID: US-' + serverOrder.order_db_id;
            document.getElementById('thankyouModal').classList.add('is-open');
            document.body.style.overflow = 'hidden';
            orderForm.reset();
          } else {
            showToast(vData.message || 'Payment verification failed. Please contact support.');
          }
        })
        .catch(err => {
          console.error(err);
          showToast('Payment verification error. Payment ID: ' + response.razorpay_payment_id);
        })
        .finally(() => {
          if (submitBtn) { submitBtn.disabled = false; submitBtn.textContent = originalText; }
        });
      },
      modal: {
        ondismiss: function () {
          if (submitBtn) { submitBtn.disabled = false; submitBtn.textContent = originalText; }
        },
      },
    };

